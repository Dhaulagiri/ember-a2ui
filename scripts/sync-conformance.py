#!/usr/bin/env python3
"""Copies A2UI's framework adapter conformance suites into the test app.

The suites live in google/A2UI under conformance/core. They're pinned to the
commit that published the @a2ui/web_core version this repo depends on, since
newer cases can test behavior that version doesn't have. Bump COMMIT with
@a2ui/web_core and run this again:

    python3 scripts/sync-conformance.py

Needs PyYAML. Writes packages/test-app/tests/conformance/suites.ts.
"""

import json
import pathlib
import urllib.request

import yaml

# chore(release): bump npm package versions for release (#3811), which
# published @a2ui/web_core 0.15.0.
COMMIT = "4fdc4c63"
REPO = "google/A2UI"
SUITES = {
    "adapter": "conformance/core/adapter_conformance.yaml",
    "accessibility": "conformance/core/accessibility.yaml",
}

out = pathlib.Path(__file__).resolve().parent.parent / (
    "packages/test-app/tests/conformance/suites.ts"
)

data = {}
for key, path in SUITES.items():
    url = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}/{path}"
    with urllib.request.urlopen(url) as response:
        data[key] = yaml.safe_load(response.read())

source = {"repo": REPO, "commit": COMMIT, "files": SUITES}
out.write_text(
    "// Generated by scripts/sync-conformance.py from A2UI's conformance suites\n"
    "// (Apache-2.0). Don't edit; run the script.\n"
    f"export const source = {json.dumps(source, indent=2)};\n\n"
    f"export const adapterCases: unknown[] = {json.dumps(data['adapter'], indent=2, ensure_ascii=False)};\n\n"
    f"export const accessibilityCases: unknown[] = {json.dumps(data['accessibility'], indent=2, ensure_ascii=False)};\n"
)
print(f"Wrote {out} from {REPO}@{COMMIT}")
